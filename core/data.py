# ── Utilitaires navigation ─────────────────────────────────────────────────────
def haversine_nm(lat1, lon1, lat2, lon2) -> float:
    R = 3440.065
    φ1, φ2 = math.radians(lat1), math.radians(lat2)
    Δφ = math.radians(lat2 - lat1)
    Δλ = math.radians(lon2 - lon1)
    a = math.sin(Δφ/2)**2 + math.cos(φ1)*math.cos(φ2)*math.sin(Δλ/2)**2
    return 2 * R * math.atan2(math.sqrt(a), math.sqrt(1-a))

def bearing_deg(lat1, lon1, lat2, lon2) -> float:
    φ1, φ2 = math.radians(lat1), math.radians(lat2)
    Δλ = math.radians(lon2 - lon1)
    x = math.sin(Δλ) * math.cos(φ2)
    y = math.cos(φ1)*math.sin(φ2) - math.sin(φ1)*math.cos(φ2)*math.cos(Δλ)
    return (math.degrees(math.atan2(x, y)) + 360) % 360

def braa_str(from_lat, from_lon, tgt_lat, tgt_lon) -> str:
    brg = bearing_deg(from_lat, from_lon, tgt_lat, tgt_lon)
    rng = haversine_nm(from_lat, from_lon, tgt_lat, tgt_lon)
    return f"{int(brg):03d} / {int(rng)} NM"

def bullseye_str(bull_lat, bull_lon, tgt_lat, tgt_lon, tgt_alt_ft=0) -> str:
    brg = bearing_deg(bull_lat, bull_lon, tgt_lat, tgt_lon)
    rng = haversine_nm(bull_lat, bull_lon, tgt_lat, tgt_lon)
    fl  = tgt_alt_ft // 1000
    return f"{int(brg):03d} / {int(rng)} / {fl:02d}0"

